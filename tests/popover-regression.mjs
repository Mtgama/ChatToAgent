import assert from 'node:assert/strict';
import { parseHTML } from 'linkedom';
import { buildMenuFixture } from './menu-bundle.mjs';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';

const { window } = parseHTML('<html><head></head><body><footer><textarea></textarea><button class="submit-btn-v2">send</button></footer></body></html>');
window.location = new URL('https://gapgpt.app/chat/test');
window.matchMedia = () => ({ matches: false, addEventListener(){}, removeEventListener(){} });
window.innerWidth = 1400; window.innerHeight = 900;
window.HTMLElement.prototype.getBoundingClientRect = () => ({ left:16, top:600, bottom:640, right:90, width:74, height:40 });
for (const name of ['window','document','HTMLElement','HTMLTextAreaElement','Event','CustomEvent']) globalThis[name] = name === 'window' ? window : window[name];
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.chrome = { runtime:{getURL:name => name} };
let copied = '';
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: { userAgent:'menu-test', clipboard: { writeText: async text => { copied = text; } } } });
const temporary = await mkdtemp(tmpdir() + '/mcp-menu-');
await writeFile(temporary + '/menu.mjs', await buildMenuFixture(true));
const { GapGPTAdapter, act, setMenuState, setMenuAdapter } = await import(pathToFileURL(temporary + '/menu.mjs'));
const adapter = new GapGPTAdapter();
let submits = 0;
document.querySelector('.submit-btn-v2').onclick = () => submits++;
document.querySelector('textarea').setSelectionRange = () => {};
await adapter.initialize({ logger:{debug(){},info(){},warn(){},error(){}}, stores:{ui:{preferences:{},updatePreferences(){}}} });
setMenuAdapter(adapter);
const tools = [{ name:'filesystem.list_allowed_directories', description:'List permitted paths', input_schema:{type:'object',properties:{}} }, { name:'memory.search_nodes', description:'Search memory', input_schema:{type:'object',properties:{query:{type:'string'}},required:['query']} }];
setMenuState({ tools, enabledTools:new Set(tools.map(tool => tool.name)) });
const click = async node => { assert.ok(node, 'Button must exist'); await act(async () => { node.click(); }); };
const action = label => [...document.querySelectorAll('[role=dialog] button')].find(node => node.textContent.trim() === label);
try {
  await act(async () => { await adapter.activate(); await adapter.activate(); });
  assert.equal(document.querySelectorAll('#mcp-gapgpt-launcher').length, 1);
  await act(async () => document.querySelector('#mcp-gapgpt-launcher button').dispatchEvent(new Event('mouseover', {bubbles:true})));
  await click(document.querySelector('#mcp-gapgpt-launcher button'));
  const dialog = document.querySelector('[role=dialog]');
  assert.ok(dialog, 'GapGPT MCP button must open the full menu');
  assert.equal(document.querySelector('.mcp-hover-overlay'), null, 'Quick actions must not cover the open menu');
  assert.match(dialog.textContent, /پرامپت پیش‌فرض ابزارها/);
  assert.match(dialog.textContent, /2 از 2 ابزار فعال/);
  assert.match(dialog.textContent, /memory.search_nodes/);
  assert.match(dialog.textContent, /"required":\["query"\]/, 'Prompt must include actual input schemas without opening the sidebar');
  assert.equal(dialog.dataset.mcpTheme, 'light');
  await click(action('درج راهنما'));
  assert.match(document.querySelector('textarea').value, /filesystem.list_allowed_directories/);
  assert.match(document.querySelector('textarea').value, /function_call_end/);
  assert.equal(submits, 0, 'Inserting instructions must never send the message automatically');
  await click(action('کپی'));
  assert.equal(copied, document.querySelector('textarea').value);
  assert.equal(action('پیوست راهنما').disabled, true, 'Unsupported attachment must be disabled on GapGPT');
  await act(async () => setMenuState({ theme:'dark', enabledTools:new Set(['filesystem.list_allowed_directories']), preferences:{customInstructionsEnabled:true,customInstructions:'فارسی پاسخ بده'} }));
  assert.equal(dialog.dataset.mcpTheme, 'dark');
  assert.match(dialog.textContent, /1 از 2 ابزار فعال/);
  assert.ok(!dialog.textContent.includes('memory.search_nodes'));
  assert.match(dialog.textContent, /فارسی پاسخ بده/);
  await act(async () => setMenuState({ tools:[], enabledTools:new Set() }));
  assert.match(dialog.textContent, /فهرست ابزارها دریافت نشده/);
  assert.ok(!dialog.textContent.includes('filesystem.list_allowed_directories'), 'Disconnected catalog must not leave a stale prompt');
  assert.equal(action('درج شد').disabled, true);
  console.log('PASS GapGPT menu: real React/portal, independent default prompt, live schemas, enabled tools, insertion without sending, clipboard, custom prompt, themes, empty state');
} finally {
  await act(async () => adapter.cleanup());
  assert.equal(document.querySelector('#mcp-gapgpt-launcher'), null);
  assert.equal(document.querySelector('#mcp-popover-portal'), null);
  await rm(temporary, { recursive:true, force:true });
}
